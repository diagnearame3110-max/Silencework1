-- Silence Work Sénégal – Migration Supabase Complète
-- Crée les tables nécessaires (produits, catégories, commandes, paramètres),
-- configure le stockage pour les photos, et active la sécurité RLS.
-- ==============================================================================

-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. TABLE DES CATÉGORIES
CREATE TABLE IF NOT EXISTS public.categories (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nom TEXT NOT NULL UNIQUE,
    ordre INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 3. TABLE DES PRODUITS SILENCE WORK
CREATE TABLE IF NOT EXISTS public.produits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    cat TEXT NOT NULL,
    prix NUMERIC(12, 0) NOT NULL,
    ancien NUMERIC(12, 0),
    "desc" TEXT,
    details JSONB NOT NULL DEFAULT '[]'::jsonb,
    visible BOOLEAN NOT NULL DEFAULT true,
    tailles JSONB NOT NULL DEFAULT '["S","M","L","XL","XXL"]'::jsonb,
    couleurs JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 4. TABLE DES COMMANDES
CREATE TABLE IF NOT EXISTS public.commandes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    numero TEXT NOT NULL UNIQUE,
    client_nom TEXT NOT NULL,
    client_tel TEXT NOT NULL,
    client_adresse TEXT NOT NULL,
    articles JSONB NOT NULL DEFAULT '[]'::jsonb,
    total NUMERIC(12, 0) NOT NULL DEFAULT 0,
    statut TEXT NOT NULL DEFAULT 'nouvelle' CHECK (statut IN ('nouvelle', 'confirmée', 'payée', 'livrée', 'annulée')),
    paiement_mode TEXT NOT NULL DEFAULT 'Wave',
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 5. TABLE DES PARAMÈTRES BOUTIQUE
CREATE TABLE IF NOT EXISTS public.parametres (
    cle TEXT PRIMARY KEY,
    valeur TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 6. INDEX POUR PERFORMANCES
CREATE INDEX IF NOT EXISTS idx_produits_cat ON public.produits(cat);
CREATE INDEX IF NOT EXISTS idx_produits_visible ON public.produits(visible);
CREATE INDEX IF NOT EXISTS idx_commandes_statut ON public.commandes(statut);
CREATE INDEX IF NOT EXISTS idx_commandes_created_at ON public.commandes(created_at DESC);

-- 7. SÉCURITÉ ROW LEVEL SECURITY (RLS)
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.produits ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.commandes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.parametres ENABLE ROW LEVEL SECURITY;

-- Politiques de lecture publique pour la boutique
DROP POLICY IF EXISTS "Lecture publique des catégories" ON public.categories;
CREATE POLICY "Lecture publique des catégories" ON public.categories
    FOR SELECT TO public USING (true);

DROP POLICY IF EXISTS "Lecture publique des produits" ON public.produits;
CREATE POLICY "Lecture publique des produits" ON public.produits
    FOR SELECT TO public USING (visible = true OR auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Lecture publique des paramètres" ON public.parametres;
CREATE POLICY "Lecture publique des paramètres" ON public.parametres
    FOR SELECT TO public USING (true);

DROP POLICY IF EXISTS "Création de commandes publique" ON public.commandes;
CREATE POLICY "Création de commandes publique" ON public.commandes
    FOR INSERT TO public WITH CHECK (true);

-- Politiques complètes pour les administrateurs connectés (Supabase Auth)
DROP POLICY IF EXISTS "Admin toutes opérations catégories" ON public.categories;
CREATE POLICY "Admin toutes opérations catégories" ON public.categories
    FOR ALL TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Admin toutes opérations produits" ON public.produits;
CREATE POLICY "Admin toutes opérations produits" ON public.produits
    FOR ALL TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Admin toutes opérations commandes" ON public.commandes;
CREATE POLICY "Admin toutes opérations commandes" ON public.commandes
    FOR ALL TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Admin toutes opérations paramètres" ON public.parametres;
CREATE POLICY "Admin toutes opérations paramètres" ON public.parametres
    FOR ALL TO authenticated USING (true) WITH CHECK (true);

-- 8. CONFIGURATION DU BUCKET SUPABASE STORAGE POUR LES PHOTOS
INSERT INTO storage.buckets (id, name, public)
VALUES ('produits', 'produits', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Politiques Storage
DROP POLICY IF EXISTS "Accès public aux photos de produits" ON storage.objects;
CREATE POLICY "Accès public aux photos de produits" ON storage.objects
    FOR SELECT TO public USING (bucket_id = 'produits');

DROP POLICY IF EXISTS "Upload photos par admin" ON storage.objects;
CREATE POLICY "Upload photos par admin" ON storage.objects
    FOR INSERT TO authenticated WITH CHECK (bucket_id = 'produits');

DROP POLICY IF EXISTS "Mise à jour photos par admin" ON storage.objects;
CREATE POLICY "Mise à jour photos par admin" ON storage.objects
    FOR UPDATE TO authenticated USING (bucket_id = 'produits');

DROP POLICY IF EXISTS "Suppression photos par admin" ON storage.objects;
CREATE POLICY "Suppression photos par admin" ON storage.objects
    FOR DELETE TO authenticated USING (bucket_id = 'produits');

